-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT zone.ID AS ENTITY_ID, zone.NAME AS ENTITY_NAME,
       zone.REGION, zone.CATEGORY, zone.ACCESS_TIER, zone.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.PARCEL_COUNT) AS PARCEL_COUNT,
       SUM(observation.DELIVERED_COUNT) AS DELIVERED_COUNT,
       SUM(observation.FAILED_COUNT) AS FAILED_COUNT,
       SUM(observation.RETURNED_COUNT) AS RETURNED_COUNT,
       SUM(observation.PARCEL_VALUE_PHP) AS PARCEL_VALUE_PHP,
       SUM(observation.DISRUPTION_HOURS) AS DISRUPTION_HOURS,
       COUNT_IF(observation.DISRUPTION_HOURS > 0) AS DISRUPTION_DAYS,
       SUM(observation.PAYOUT_DUE) AS PAYOUT_DUE,
       SUM(observation.PAYOUT_SETTLED) AS PAYOUT_SETTLED,
       100.0 * SUM(observation.DELIVERED_COUNT) / NULLIF(SUM(observation.PARCEL_COUNT), 0) AS SUCCESS_PCT,
       100.0 * SUM(observation.RETURNED_COUNT) / NULLIF(SUM(observation.PARCEL_COUNT), 0) AS RETURN_PCT,
       100.0 * SUM(observation.PAYOUT_SETTLED) / NULLIF(SUM(observation.PAYOUT_DUE), 0) AS PAYOUT_ON_TIME_PCT,
       AVG(observation.AVG_ATTEMPTS) AS AVG_ATTEMPTS,
       AVG(observation.AVG_DELIVERY_HOURS) AS AVG_DELIVERY_HOURS,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.ZONE_DAILY observation
JOIN RAW.ZONES zone ON zone.ID = observation.ENTITY_ID
GROUP BY zone.ID, zone.NAME, zone.REGION, zone.CATEGORY, zone.ACCESS_TIER, zone.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(PARCEL_COUNT) AS PARCEL_COUNT, SUM(DELIVERED_COUNT) AS DELIVERED_COUNT,
       SUM(FAILED_COUNT) AS FAILED_COUNT, SUM(DISRUPTION_HOURS) AS DISRUPTION_HOURS,
       SUM(PARCEL_VALUE_PHP) AS PARCEL_VALUE_PHP,
       100.0 * SUM(DELIVERED_COUNT) / NULLIF(SUM(PARCEL_COUNT), 0) AS SUCCESS_PCT
FROM RAW.ZONE_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.CAUSE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT DISRUPTION_CAUSE, COUNT(*) AS DISRUPTION_DAYS,
       SUM(DISRUPTION_HOURS) AS DISRUPTION_HOURS,
       SUM(FAILED_COUNT) AS FAILED_COUNT,
       SUM(PARCEL_COUNT) AS PARCEL_COUNT,
       100.0 * SUM(FAILED_COUNT) / NULLIF(SUM(PARCEL_COUNT), 0) AS FAILED_PCT
FROM RAW.ZONE_DAILY
WHERE DISRUPTION_HOURS > 0
GROUP BY DISRUPTION_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(PARCEL_COUNT) AS PARCELS, SUM(DELIVERED_COUNT) AS DELIVERED,
         SUM(FAILED_COUNT) AS FAILED, SUM(RETURNED_COUNT) AS RETURNED,
         SUM(DISRUPTION_HOURS) AS DISRUPTION_HOURS, COUNT_IF(DISRUPTION_HOURS > 0) AS DISRUPTION_DAYS,
         SUM(PARCEL_VALUE_PHP) AS PARCEL_VALUE_PHP, SUM(PAYOUT_DUE) AS PAYOUT_DUE, SUM(PAYOUT_SETTLED) AS PAYOUT_SETTLED,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.ZONE_DAILY
), book AS (SELECT COUNT(*) AS ZONE_COUNT FROM RAW.ZONES),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.RIDER_DOCUMENTS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Delivery Success Rate' AS TITLE,
         100.0 * DELIVERED / NULLIF(PARCELS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Failed Deliveries', FAILED, '' FROM observations
  UNION ALL SELECT 3, 'Delivery Disruption Hours', DISRUPTION_HOURS, '' FROM observations
  UNION ALL SELECT 4, 'Return to Sender Rate', 100.0 * RETURNED / NULLIF(PARCELS, 0), '%' FROM observations
  UNION ALL SELECT 5, 'Disruption Zone-Days', DISRUPTION_DAYS, '' FROM observations
  UNION ALL SELECT 6, 'Delivered Value (PHP M)', PARCEL_VALUE_PHP / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Parcels Delivered', DELIVERED, '' FROM observations
  UNION ALL SELECT 8, 'Rider Payout On-Time Rate', 100.0 * PAYOUT_SETTLED / NULLIF(PAYOUT_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Zones Monitored', ZONE_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Rider Document Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Rider Documents Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.CAUSE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
